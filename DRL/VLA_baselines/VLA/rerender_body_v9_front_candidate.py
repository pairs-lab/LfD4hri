"""Immutable FRONT-only derivative of a V9 candidate.

Exact stored actions are replayed, never regenerated by a teacher. This
proves camera-only equivalence; it does NOT certify data for fine-tuning.
"""
from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

import numpy as np

from VLA.common.body_environment import BodyGraspEnvironment
from VLA.common.observation_profile import profile_hash, validate_profile
from VLA.common.provenance import sha256_file
from VLA.common.runtime_provenance import environment_runtime_fingerprint, verify_environment_runtime_fingerprint
from VLA.common.source_payload_provenance import source_payload_fingerprint, verify_source_payload_fingerprint
from VLA.common.tasks import TaskSpec


NUMERIC_TOLERANCE = 1e-6
FRONT_FIELDS = ("front_rgb", "front_pick_mask", "front_place_mask", "front_robot_mask")
REQUIRED_FIELDS = FRONT_FIELDS + (
    "wrist_rgb", "wrist_pick_mask", "wrist_place_mask", "wrist_robot_mask",
    "joint_positions", "ee_position", "ee_rotation_6d", "gripper_closure", "gripper_open",
    "canonical_actions", "next_joint_targets", "next_observed_joint_positions",
    "next_gripper_closure", "next_requested_gripper_closure", "next_ee_object_distance",
    "next_object_goal_distance", "next_touching_object", "next_grasped_object",
    "next_raw_success", "next_success_streak", "next_bilateral_pad_contact",
    "next_verified_grasp", "rewards", "prompt",
)


def front_only_profile(old_profile, candidate):
    old, new = validate_profile(old_profile), validate_profile(candidate)
    if old.get("gripper_controller") != "body_contact_v9":
        raise ValueError("An explicit body_contact_v9 source profile is required")
    for profile in (old, new):
        profile.pop("name", None)
        profile["cameras"].pop("front")
    if old != new:
        raise ValueError("Only profile name and FRONT camera may differ; home/wrist/physics/overview are immutable")
    return validate_profile(candidate)


def successful_raw_rows(rows, profile_identity, required_steps, allow_paired=False):
    if not isinstance(rows, list) or not rows:
        raise ValueError("A nonempty raw source index is required")
    for row in rows:
        if not row.get("success") or row.get("safety_violation"):
            raise ValueError("All source episodes must be successful without safety aborts")
        if "camera_only_derivative_of" in row:
            raise ValueError("Use the original uncropped/underived source, not a chained camera derivative")
        paired = any(key in row for key in ("paired_scene_source", "recovery_start_actions_not_training_labels"))
        if paired and not allow_paired:
            raise ValueError("This utility accepts unpaired raw episodes only")
        if paired and (not row.get("paired_scene_source")
                       or row.get("paired_reset_strategy") != "canonical_spawn_order_then_teacher_retarget"
                       or row.get("variant") not in (0, 1)):
            raise ValueError("Paired derivative needs explicit canonical reset/variant provenance")
        if row.get("observation_profile_sha256") != profile_identity:
            raise ValueError("Source episode profile identity differs from its manifest")
        if row.get("success_contract", {}).get("required_consecutive_steps") != required_steps:
            raise ValueError("Source episode success streak differs from its manifest")


def write_json(path, value):
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def numeric_check(actual, expected, label, maxima):
    actual, expected = np.asarray(actual), np.asarray(expected)
    if actual.shape != expected.shape or not np.isfinite(actual).all() or not np.isfinite(expected).all():
        raise RuntimeError(f"Invalid shape/nonfinite numeric replay field: {label}")
    error = float(np.max(np.abs(actual.astype(float)-expected.astype(float))))
    maxima["numeric_max_abs_error"] = max(maxima["numeric_max_abs_error"], error)
    if error > NUMERIC_TOLERANCE:
        raise RuntimeError(f"Numeric replay mismatch {label}: {error}")


def exact_check(actual, expected, label):
    if not np.array_equal(np.asarray(actual), np.asarray(expected)):
        raise RuntimeError(f"Exact replay label/mask mismatch: {label}")


def wrist_check(rgb, expected, masks, expected_masks, label, maxima):
    rgb, expected = np.asarray(rgb), np.asarray(expected)
    if rgb.shape != expected.shape or rgb.dtype != np.uint8 or expected.dtype != np.uint8:
        raise RuntimeError(f"Invalid wrist RGB shape/dtype: {label}")
    error = int(np.max(np.abs(rgb.astype(np.int16)-expected.astype(np.int16))))
    fraction = float(np.any(rgb != expected, axis=-1).mean())
    maxima["wrist_max_channel_lsb"] = max(maxima["wrist_max_channel_lsb"], error)
    maxima["wrist_max_changed_pixel_fraction"] = max(maxima["wrist_max_changed_pixel_fraction"], fraction)
    if error > 1 or fraction > .001:
        raise RuntimeError(f"Unchanged wrist RGB differs {label}: lsb={error}, fraction={fraction}")
    for kind in ("pick", "place", "robot"):
        exact_check(masks[kind], expected_masks[kind], f"{label}:wrist_{kind}_mask")


def replay_episode(env, item, arrays, maxima, reset_source=None):
    missing = set(REQUIRED_FIELDS)-set(arrays)
    if missing:
        raise ValueError("Raw V9 episode fields missing: " + ", ".join(sorted(missing)))
    actions = arrays["canonical_actions"]
    count = len(actions)
    if count != item["steps"] or actions.shape != (count, 7) or not count:
        raise ValueError("Episode action count/shape differs from source index")
    for key in REQUIRED_FIELDS:
        if key != "prompt" and len(arrays[key]) != count:
            raise ValueError("Episode transition field length differs: " + key)
    task = TaskSpec.from_dict(item["task"])
    exact_check(arrays["prompt"], task.prompt, "prompt")
    if reset_source is not None:
        from VLA.dataset_replay_context import reset_source_episode
        observation = reset_source_episode(env, reset_source, item)
    else:
        observation = env.reset(task)
        from VLA.common.success_contract_snapshot import recorded_distance_thresholds
        env.dist_threshold, env.obj_threshold = recorded_distance_thresholds(item)
    if "overview_reset_robot_mask" in arrays:
        env.render("overview")
        exact_check(env.robot_mask("overview"), arrays["overview_reset_robot_mask"], "overview_reset_robot_mask")
    rendered = {key: [] for key in FRONT_FIELDS}
    wrists = []
    done, info = False, None
    for frame, action in enumerate(actions):
        label = f"{item['file']}:{frame}"
        for key in ("joint_positions", "ee_position", "ee_rotation_6d"):
            numeric_check(getattr(observation, key), arrays[key][frame], f"{label}:{key}", maxima)
        numeric_check(env.normalized_gripper_closure(), arrays["gripper_closure"][frame], label+":gripper_closure", maxima)
        exact_check(observation.gripper_open, arrays["gripper_open"][frame], label+":gripper_open")
        masks = {kind: env.target_mask("wrist", kind) for kind in ("pick", "place")}
        masks["robot"] = env.robot_mask("wrist")
        wrist_check(observation.wrist_rgb, arrays["wrist_rgb"][frame], masks,
                    {kind: arrays[f"wrist_{kind}_mask"][frame] for kind in masks}, label, maxima)
        wrists.append(observation.wrist_rgb.copy())
        rendered["front_rgb"].append(observation.front_rgb.copy())
        for kind in ("pick", "place"):
            rendered[f"front_{kind}_mask"].append(env.target_mask("front", kind).copy())
        rendered["front_robot_mask"].append(env.robot_mask("front").copy())
        observation, reward, done, info = env.step(action)
        if info.get("safety_violation"):
            raise RuntimeError(f"Safety abort during camera-only replay {label}: {info['safety_violation']}")
        numeric = {
            "next_joint_targets": env.requested_arm_targets,
            "next_observed_joint_positions": observation.joint_positions,
            "next_gripper_closure": env.normalized_gripper_closure(),
            "next_requested_gripper_closure": env.commanded_gripper_closure(),
            "next_ee_object_distance": info["ee_object_distance"],
            "next_object_goal_distance": info["object_goal_distance"],
            "rewards": reward,
        }
        for key, actual in numeric.items():
            numeric_check(actual, arrays[key][frame], f"{label}:{key}", maxima)
        numeric_check(info["executed_canonical_action"], action, label+":executed_action", maxima)
        bilateral = env.gripper._bilateral(env.pick_id)
        grasped = info["grasped_object"] == env.pick_id
        exact = {"next_touching_object": info["touching_object"], "next_grasped_object": grasped,
                 "next_raw_success": info["raw_success"], "next_success_streak": info["success_streak"],
                 "next_bilateral_pad_contact": bilateral, "next_verified_grasp": bilateral and grasped}
        for key, actual in exact.items():
            exact_check(actual, arrays[key][frame], f"{label}:{key}")
        if done and frame != count-1:
            raise RuntimeError("Camera-only replay terminated earlier than source: " + label)
    if not done or not info["success"]:
        raise RuntimeError("Camera-only replay terminal success differs from source")
    result = dict(arrays)
    result.update({key: np.asarray(values) for key, values in rendered.items()})
    result["wrist_rgb"] = np.asarray(wrists)
    # No stale pixels: save actual new wrist RGB (allowing only tiny 1-LSB
    # renderer rounding), but require every other non-front field exact.
    for key in arrays:
        if key not in FRONT_FIELDS and key != "wrist_rgb":
            exact_check(result[key], arrays[key], "unchanged_payload:"+key)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--workers", type=int, default=1,
                        help="Independent spawned PyBullet processes (1–16); default serial replay")
    parser.add_argument("--paired-reset", action="store_true",
                        help="Opt-in exact canonical spawn/startup replay for paired recovery data; never regenerate labels")
    args = parser.parse_args()
    if not 1 <= args.workers <= 16:
        raise ValueError("workers must be between one and sixteen")
    source, output = args.source.resolve(), args.output.resolve()
    if output == source or source in output.parents:
        raise ValueError("Derivative output cannot be the source or a source subdirectory")
    manifest = json.loads((source/"dataset_manifest.json").read_text())
    rows = json.loads((source/"index.json").read_text())
    old_profile = manifest["observation_profile"]
    profile = front_only_profile(old_profile, json.loads(args.profile.read_text()))
    old_identity, identity = profile_hash(old_profile), profile_hash(profile)
    if manifest.get("observation_profile_sha256") != old_identity:
        raise ValueError("Source manifest profile hash is inconsistent")
    streak = manifest["required_success_steps"]
    if type(streak) is not int or streak < 1:
        raise ValueError("Positive integer source success streak required")
    successful_raw_rows(rows, old_identity, streak, args.paired_reset)
    reset_parents = {}
    paired_provenance = {}
    if args.paired_reset:
        from VLA.audit_training_readiness import source_reset_provenance
        for row in rows:
            provenance = source_reset_provenance(source, row)
            if not provenance:
                raise ValueError("Paired mode cannot contain ambiguous RAW reset rows")
            reset_parents[provenance["canonical_source"]] = provenance["canonical_source_index_sha256"]
            paired_provenance[row["file"]] = provenance
    runtime = environment_runtime_fingerprint(profile)
    verify_environment_runtime_fingerprint(manifest.get("environment_runtime_fingerprint"), old_profile)
    payload = source_payload_fingerprint(source, rows)
    binding = {"source":str(source), "source_index_sha256":sha256_file(source/"index.json"),
        "source_manifest_sha256":sha256_file(source/"dataset_manifest.json"),
        "source_payload_fingerprint":payload, "environment_runtime_fingerprint":runtime,
        "observation_profile_sha256":identity, "image_size":manifest["image_size"],
        "required_success_steps":streak, "seed":manifest["seed"],
        "canonical_reset_parents":reset_parents}
    if args.paired_reset:
        binding["paired_row_reset_provenance"] = paired_provenance
    if output.exists() and not args.resume:
        raise FileExistsError(output)
    output.mkdir(parents=True, exist_ok=True)
    from VLA.front_derivative_worker import coordinator_lock
    with coordinator_lock(output):
        return generate_derivative(args, manifest, rows, profile, identity, binding)


def generate_derivative(args, manifest, rows, profile, identity, binding):
    """Only the locked coordinator commits ordered index/checkpoint metadata."""
    from VLA.front_derivative_worker import (
        bounded_process_replays, derivative_metadata, merge_replay_errors,
        produce_episode_receipt, receipt_path, safe_destination,
        validate_replay_errors, verify_episode_receipt,
    )
    source, output = Path(binding["source"]), args.output.resolve()
    payload, runtime = binding["source_payload_fingerprint"], binding["environment_runtime_fingerprint"]
    reset_parents, streak = binding["canonical_reset_parents"], binding["required_success_steps"]
    maxima = {"numeric_max_abs_error":0., "wrist_max_channel_lsb":0, "wrist_max_changed_pixel_fraction":0.}
    completed = []
    if args.resume:
        state = json.loads((output/"collection_state.json").read_text())
        if state.get("binding") != binding:
            raise RuntimeError("Resume source/profile/runtime/payload identity differs")
        completed = json.loads((output/"index.json").read_text())
        maxima = state["exact_replay_errors"]
        validate_replay_errors(maxima)
        state_count = state.get("completed_episodes")
        if type(state_count) is not int or not 0 <= state_count <= len(completed):
            raise RuntimeError("Resume progress/index count differs")
        for number, item in enumerate(completed):
            if number >= len(rows) or item["file"] != rows[number]["file"]:
                raise RuntimeError("Resume index is not a committed source prefix")
            expected = derivative_metadata(rows[number], binding, item.get("camera_derivative_output_sha256"))
            if item != expected:
                raise RuntimeError("Resume output metadata/labels contain a mixed derivative")
            path = safe_destination(output, item["file"])
            if path.is_symlink() or sha256_file(path) != item.get("camera_derivative_output_sha256"):
                raise RuntimeError("Committed resume payload differs: " + item["file"])
            receipt_file = receipt_path(output, item["file"])
            if receipt_file.exists() or receipt_file.is_symlink() or number >= state_count:
                # Legacy committed serial prefixes are accepted by their
                # binding + exact metadata + output hash. A crash AFTER index
                # publication but BEFORE state publication additionally needs
                # the successful worker receipt to recover that new suffix.
                receipt = verify_episode_receipt(output, rows[number], number, binding)
                merge_replay_errors(maxima, receipt["exact_replay_errors"])

    def checkpoint(status):
        write_json(output/"index.json", completed)
        write_json(output/"collection_state.json", {"status":status, "binding":binding,
            "completed_episodes":len(completed), "planned_episodes":len(rows),
            "exact_replay_errors":maxima, "not_qualified_for_training_yet":True,
            "workers_requested":args.workers})

    checkpoint("in_progress")
    try:
        ready, jobs = {}, []
        for number in range(len(completed), len(rows)):
            item = rows[number]
            destination, receipt_file = safe_destination(output, item["file"]), receipt_path(output, item["file"])
            if destination.exists() or receipt_file.exists() or receipt_file.is_symlink():
                if not args.resume:
                    raise FileExistsError("Uncommitted output payload preserved; refusing overwrite: "+str(destination))
                ready[number] = verify_episode_receipt(output, item, number, binding)
            elif receipt_file.with_name(receipt_file.name+".tmp").exists():
                raise FileExistsError("Unverified partial receipt preserved: "+str(receipt_file))
            else:
                jobs.append((number, item))

        def commit_ready_prefix():
            while len(completed) in ready:
                number = len(completed)
                receipt = ready.pop(number)
                # Rehash saved receipt/payload BEFORE every coordinator commit.
                receipt = verify_episode_receipt(output, rows[number], number, binding, receipt)
                merge_replay_errors(maxima, receipt["exact_replay_errors"])
                completed.append(receipt["metadata"])
                checkpoint("in_progress")
                print(f"FRONT-only exact replay {number+1}/{len(rows)}: {rows[number]['file']}", flush=True)

        commit_ready_prefix()
        if args.workers == 1 and jobs:
            with BodyGraspEnvironment(profile, robot=manifest["robot"], image_size=manifest["image_size"],
                    seed=manifest["seed"], required_success_steps=streak, use_semantic_success=False) as env:
                for number, item in jobs:
                    ready[number] = produce_episode_receipt(env, item, number, source, output,
                                                           profile, binding, replay_episode)
                    commit_ready_prefix()
        elif jobs:
            for number, receipt in bounded_process_replays(jobs, source, output, manifest, profile, binding, args.workers):
                ready[number] = receipt
                commit_ready_prefix()
        if len(completed) != len(rows) or ready:
            raise RuntimeError("Ordered derivative prefix did not complete every source episode")
        if sha256_file(source/"index.json") != binding["source_index_sha256"] or sha256_file(source/"dataset_manifest.json") != binding["source_manifest_sha256"]:
            raise RuntimeError("Source index/manifest changed during derivative generation")
        verify_source_payload_fingerprint(payload, source, rows)
        for parent, expected in reset_parents.items():
            if sha256_file(Path(parent)/"index.json") != expected:
                raise RuntimeError("Canonical reset parent changed during paired derivative")
        verify_environment_runtime_fingerprint(runtime, profile)
        new_manifest = copy.deepcopy(manifest)
        new_manifest.update(candidate_only=True, observation_profile=profile,
            observation_profile_sha256=identity, cameras=profile["cameras"],
            index_sha256=sha256_file(output/"index.json"), environment_runtime_fingerprint=runtime,
            camera_only_derivative_of=str(source), derivative_source_index_sha256=binding["source_index_sha256"],
            derivative_source_manifest_sha256=binding["source_manifest_sha256"],
            derivative_source_payload_fingerprint=payload,
            training_certified=False, derivative_scope="front_camera_only_exact_stored_action_replay")
        write_json(output/"dataset_manifest.json", new_manifest)
        report = {"passed":True, "scope":"front_camera_only_exact_stored_action_replay",
            "training_certified":False, "not_qualified_for_training_yet":True,
            "camera_only_derivative_of":str(source), "observation_profile":profile,
            "observation_profile_sha256":identity, "environment_runtime_fingerprint":runtime,
            "derivative_source_index_sha256":binding["source_index_sha256"],
            "derivative_source_manifest_sha256":binding["source_manifest_sha256"],
            "derivative_source_payload_fingerprint":payload, "exact_replay_errors":maxima,
            "episodes":len(completed), "numeric_tolerance":NUMERIC_TOLERANCE,
            "wrist_rgb_rounding_gate":{"max_channel_lsb":1,"max_changed_pixel_fraction":.001,
                "all_wrist_masks_exact":True,"actual_new_pixels_saved":True},
            "numeric_actions_states_labels_unchanged":True,
            "source_payload_verified_before_and_after":True,"runtime_verified_before_and_after":True,
            "canonical_reset_parents":reset_parents,
            "worker_receipts_verified_before_commit":True, "workers_requested":args.workers,
            "process_isolation": "spawned_independent_pybullet_clients" if args.workers > 1 else "serial",
            "source_modified":False, "legacy_or_rl_changed":False, "final_test_used":False}
        write_json(output/"audit.json", report)
        checkpoint("completed_camera_only_candidate_audit_passed")
    except BaseException as exc:
        checkpoint("failed_partial_preserved")
        write_json(output/"audit.json", {"passed":False,"training_certified":False,
            "scope":"front_camera_only_exact_stored_action_replay","error":str(exc),
            "completed_episodes":len(completed),"binding":binding,"exact_replay_errors":maxima,
            "partial_preserved":True})
        raise


if __name__ == "__main__":
    main()
